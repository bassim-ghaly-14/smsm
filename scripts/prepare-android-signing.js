#!/usr/bin/env node
/**
 * Patches the Expo prebuilt `android/app/build.gradle` so that the release
 * build type uses a `signingConfigs.release` entry instead of the debug
 * keystore.
 *
 * Safe to re-run. It only inserts a `release` signing config when a keystore
 * already exists at the standard location; otherwise it does nothing and
 * leaves the generated (unsigned / debug-keystore) build untouched.
 *
 * Run AFTER `npx expo prebuild --clean -p android` and BEFORE
 * `./gradlew :app:assembleRelease`.
 *
 * The release keystore must be written to:
 *   android/app/smsm-release-keystore.jks
 * (e.g. `base64 -d <<< "$ANDROID_KEYSTORE_BASE64" > android/app/smsm-release-keystore.jks`)
 *
 * Never commit this file or the keystore. Both are git-ignored by default.
 */

'use strict';

const fs = require('fs');
const path = require('path');

const androidAppBuildGradle = path.resolve(
  __dirname,
  '..',
  'android',
  'app',
  'build.gradle'
);

// Path of the release keystore, relative to the repository root.
const KEYSTORE_RELATIVE = 'android/app/smsm-release-keystore.jks';
const keystorePath = path.resolve(__dirname, KEYSTORE_RELATIVE);

if (!fs.existsSync(keystorePath)) {
  console.warn(
    `prepare-android-signing: keystore not found at "${keystorePath}". ` +
      'Skipping release signing config patch (no signing configured).'
  );
  process.exit(0);
}

let content = fs.readFileSync(androidAppBuildGradle, 'utf8');

// ---------------------------------------------------------------------------
// 1) Inject a `release` entry inside the existing `signingConfigs { }` block.
//    The generated file already declares `signingConfigs { debug { ... } }`.
//    We must NOT create a second `signingConfigs` block (Groovy DSL conflict).
// ---------------------------------------------------------------------------
const debugSigningBlock = `        debug {
            storeFile file('debug.keystore')
            storePassword 'android'
            keyAlias 'androiddebugkey'
            keyPassword 'android'
        }
    }`;

const releaseSigningEntry = `        debug {
            storeFile file('debug.keystore')
            storePassword 'android'
            keyAlias 'androiddebugkey'
            keyPassword 'android'
        }
        release {
            // Stable release keystore (generated by the developer, never committed).
            // It must live at android/app/smsm-release-keystore.jks.
            def keystorePath = rootProject.file('app/smsm-release-keystore.jks').absolutePath
            storeFile file(keystorePath)
            storePassword System.getenv('ANDROID_KEYSTORE_PASSWORD')
            keyAlias System.getenv('ANDROID_KEY_ALIAS')
            keyPassword System.getenv('ANDROID_KEY_PASSWORD')
        }
    }`;

if (!content.includes(debugSigningBlock)) {
  throw new Error(
    'Could not locate the existing `signingConfigs { debug { ... } }` block in ' +
      androidAppBuildGradle +
      '. Is this an Expo prebuilt Android project? (Run `npx expo prebuild --clean -p android` first.)'
  );
}

content = content.replace(debugSigningBlock, releaseSigningEntry);

// ---------------------------------------------------------------------------
// 2) Point the release build type at the release signing config instead of
//    the debug keystore. This exact two-line sequence only appears in the
//    generated release build type (the debug build type ends with `}`).
// ---------------------------------------------------------------------------
const releaseSigningAnchor =
  '            signingConfig signingConfigs.debug\n            def enableShrinkResources';
const releaseSigningReplacement =
  '            signingConfig signingConfigs.release\n            def enableShrinkResources';

if (!content.includes(releaseSigningAnchor)) {
  throw new Error(
    'Could not locate the release build-type signing anchor in ' +
      androidAppBuildGradle +
      '. Expected `signingConfig signingConfigs.debug` followed by `def enableShrinkResources`.'
  );
}

content = content.replace(releaseSigningAnchor, releaseSigningReplacement);

fs.writeFileSync(androidAppBuildGradle, content, 'utf8');

console.log(`prepare-android-signing: patched ${androidAppBuildGradle}`);
console.log('  - release build type now uses signingConfigs.release');
console.log('  - signingConfigs.release reads android/app/smsm-release-keystore.jks');
